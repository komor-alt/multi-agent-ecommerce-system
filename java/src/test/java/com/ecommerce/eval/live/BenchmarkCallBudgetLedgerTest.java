package com.ecommerce.eval.live;

import com.ecommerce.service.LlmCallBudget;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicInteger;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class BenchmarkCallBudgetLedgerTest {
    private static final String NAMESPACE = "bench_test_revision_config_00000001";
    private static final String REVISION = "272744f1546edd83cb45475eabddddc4121c4022";
    private static final String CONFIG = "a".repeat(64);
    private JdbcTemplate jdbc;
    private BenchmarkCallBudgetLedger ledger;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource source = new DriverManagerDataSource(
                "jdbc:h2:mem:benchmark_" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("create table benchmark_execution_sessions(namespace varchar(180) primary key, "
                + "revision varchar(40) not null, config_hash varchar(64) not null, dataset_hash varchar(64) not null, "
                + "scope varchar(16) not null, arm_set varchar(16) not null, case_count integer not null, "
                + "arm_count integer not null, per_case_budget integer not null, total_budget integer not null, "
                + "status varchar(16) not null, created_at timestamp default current_timestamp, completed_at timestamp)");
        jdbc.execute("create table benchmark_run_manifests(run_id varchar(255) primary key, namespace varchar(180) not null, "
                + "arm varchar(160) not null, case_id varchar(160) not null, topology varchar(32) not null, "
                + "revision varchar(40) not null, config_hash varchar(64) not null, status varchar(16) not null, "
                + "created_at timestamp default current_timestamp, completed_at timestamp, unique(namespace,arm,case_id))");
        jdbc.execute("create table benchmark_provider_call_claims(id bigint generated by default as identity primary key, "
                + "namespace varchar(180) not null, run_id varchar(255) not null, arm varchar(160) not null, "
                + "fingerprint_hash varchar(64) not null, created_at timestamp default current_timestamp, "
                + "unique(run_id,fingerprint_hash))");
        jdbc.update("insert into benchmark_execution_sessions(namespace,revision,config_hash,dataset_hash,scope,arm_set,"
                        + "case_count,arm_count,per_case_budget,total_budget,status) values (?,?,?,?,?,?,?,?,?,?,?)",
                NAMESPACE, REVISION, CONFIG, "b".repeat(64), "SMOKE", "CORE", 2, 2, 2, 8, "RUNNING");
        ledger = new BenchmarkCallBudgetLedger(jdbc, new DataSourceTransactionManager(source),
                NAMESPACE, REVISION, CONFIG, 2, 2, 2, 8);
    }

    @Test
    void mockProviderCannotExceedCaseBudgetOrRepeatAFingerprint() {
        String runId = run("single", "case-1");
        AtomicInteger providerCalls = new AtomicInteger();
        LlmCallBudget budget = new LlmCallBudget(2,
                (phase, fingerprint) -> ledger.reserve(runId, phase, fingerprint));

        assertThat(mockProviderCall(budget, providerCalls, "planner", "one")).isTrue();
        assertThat(mockProviderCall(budget, providerCalls, "planner", "one")).isFalse();
        assertThat(mockProviderCall(budget, providerCalls, "planner", "two")).isTrue();
        assertThat(mockProviderCall(budget, providerCalls, "planner", "three")).isFalse();

        assertThat(providerCalls).hasValue(2);
        assertThat(ledger.snapshot()).containsEntry("providerCallClaims", 2L);
        assertThat(budget.snapshot()).containsEntry("llmCallCount", 2)
                .containsEntry("duplicateCallsBlocked", 1)
                .containsEntry("budgetBlockedCalls", 1);
    }

    @Test
    void concurrentReservationsStayWithinTheDurableBudget() throws Exception {
        String runId = run("single", "case-1");
        var workers = Executors.newFixedThreadPool(8);
        try {
            List<Callable<LlmCallBudget.Reservation>> calls = new ArrayList<>();
            for (int index = 0; index < 24; index++) {
                int call = index;
                calls.add(() -> ledger.reserve(runId, "planner", "call-" + call));
            }
            List<LlmCallBudget.Reservation> results = workers.invokeAll(calls).stream().map(future -> {
                try { return future.get(); } catch (Exception error) { throw new AssertionError(error); }
            }).toList();
            assertThat(results.stream().filter(LlmCallBudget.Reservation::acquired)).hasSize(2);
            assertThat(ledger.snapshot()).containsEntry("providerCallClaims", 2L);
        } finally {
            workers.shutdownNow();
        }
    }

    @Test
    void duplicateRunArmOverflowAndCrossRevisionResumeFailClosed() {
        String first = run("single", "case-1");
        assertThatThrownBy(() -> ledger.registerRun(first, "single", "case-1", "single"))
                .hasMessageContaining("duplicate benchmark Run");
        run("single", "case-2");
        assertThatThrownBy(() -> run("single", "case-3"))
                .hasMessageContaining("complete case set");

        jdbc.update("update benchmark_execution_sessions set revision=? where namespace=?",
                "f".repeat(40), NAMESPACE);
        assertThatThrownBy(() -> ledger.reserve(first, "planner", "new-call"))
                .hasMessageContaining("identity mismatch");
    }

    @Test
    void abortedRunCannotInvokeMockProviderAgain() {
        String runId = run("multi", "case-1");
        LlmCallBudget budget = new LlmCallBudget(2,
                (phase, fingerprint) -> ledger.reserve(runId, phase, fingerprint));
        assertThat(budget.reserve("supervisor", "one").acquired()).isTrue();

        ledger.abortRun(runId, "fixture_abort");

        assertThatThrownBy(() -> budget.reserve("supervisor", "two"))
                .hasMessageContaining("Run is not active");
        assertThat(jdbc.queryForObject("select status from benchmark_run_manifests where run_id=?",
                String.class, runId)).isEqualTo("ABORTED");
    }

    @Test
    void topologyMismatchIsRejectedBeforeAProviderBudgetIsCreated() {
        String runId = run("single", "case-1");
        ledger.verifyRunIdentity(runId, "single");
        assertThatThrownBy(() -> ledger.verifyRunIdentity(runId, "multi"))
                .hasMessageContaining("topology mismatch");
        assertThat(ledger.snapshot()).containsEntry("providerCallClaims", 0L);
    }

    private String run(String arm, String caseId) {
        String runId = NAMESPACE + "__" + arm + "__" + caseId;
        ledger.registerRun(runId, arm, caseId, arm);
        return runId;
    }

    private boolean mockProviderCall(LlmCallBudget budget, AtomicInteger providerCalls,
                                     String phase, String fingerprint) {
        LlmCallBudget.Reservation reservation = budget.reserve(phase, fingerprint);
        if (!reservation.acquired()) return false;
        providerCalls.incrementAndGet();
        return true;
    }
}
